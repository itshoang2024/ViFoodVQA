from __future__ import annotations

import argparse
import json
import shutil
from collections import Counter
from datetime import datetime, timezone
from pathlib import Path
from typing import Any


BACKUP_ROOT = "_prune_backups"


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Remove incident-affected VQA rows from ViFoodVQA prediction JSONL files."
    )
    parser.add_argument(
        "--outputs-dir",
        type=Path,
        default=Path("outputs"),
        help="Evaluation outputs directory. Default: outputs",
    )
    parser.add_argument(
        "--incident-json",
        type=Path,
        required=True,
        help="Path to affected_test_vqa.json generated by the KG triple cascade script.",
    )
    parser.add_argument(
        "--apply",
        action="store_true",
        help="Write pruned files. Default is dry-run only.",
    )
    parser.add_argument(
        "--run-id",
        default=None,
        help="Stable id for backup/report directory. Defaults to UTC timestamp.",
    )
    args = parser.parse_args()

    outputs_dir = args.outputs_dir.resolve()
    incident_path = args.incident_json.resolve()
    run_id = args.run_id or datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    affected_ids = load_affected_vqa_ids(incident_path)
    prediction_files = find_prediction_files(outputs_dir)

    report = prune_prediction_files(
        prediction_files=prediction_files,
        affected_ids=affected_ids,
        outputs_dir=outputs_dir,
        run_id=run_id,
        apply=args.apply,
    )
    report.update(
        {
            "mode": "apply" if args.apply else "dry-run",
            "run_id": run_id,
            "incident_json": str(incident_path),
            "affected_vqa_ids": sorted(affected_ids),
            "prediction_files_checked": len(prediction_files),
        }
    )

    report_path = outputs_dir / f"prune_report_{run_id}.json"
    report_path.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, ensure_ascii=False, indent=2))
    print(f"Wrote prune report to {report_path}")


def load_affected_vqa_ids(path: Path) -> set[int]:
    rows = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(rows, list):
        raise ValueError(f"Expected a JSON array in {path}")

    ids: set[int] = set()
    for row in rows:
        if not isinstance(row, dict) or row.get("vqa_id") is None:
            continue
        ids.add(int(row["vqa_id"]))
    if not ids:
        raise ValueError(f"No vqa_id values found in {path}")
    return ids


def find_prediction_files(outputs_dir: Path) -> list[Path]:
    files: list[Path] = []
    for path in outputs_dir.rglob("*.jsonl"):
        parts = set(path.parts)
        if BACKUP_ROOT in parts or "classifier" in parts:
            continue
        if "__" not in path.name:
            continue
        files.append(path)
    return sorted(files)


def prune_prediction_files(
    *,
    prediction_files: list[Path],
    affected_ids: set[int],
    outputs_dir: Path,
    run_id: str,
    apply: bool,
) -> dict[str, Any]:
    backup_dir = outputs_dir / BACKUP_ROOT / run_id
    file_reports: list[dict[str, Any]] = []
    hit_counts: Counter[int] = Counter()
    total_removed = 0

    for path in prediction_files:
        rows = load_jsonl(path)
        kept: list[dict[str, Any]] = []
        removed: list[dict[str, Any]] = []
        for row in rows:
            try:
                vqa_id = int(row.get("vqa_id"))
            except (TypeError, ValueError):
                vqa_id = None
            if vqa_id in affected_ids:
                removed.append(row)
            else:
                kept.append(row)

        removed_ids = sorted(int(row["vqa_id"]) for row in removed if row.get("vqa_id") is not None)
        missing_ids = sorted(affected_ids - set(removed_ids))
        total_removed += len(removed)
        hit_counts[len(removed)] += 1

        if apply and removed:
            backup_path = backup_dir / path.relative_to(outputs_dir)
            backup_path.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(path, backup_path)
            write_jsonl(path, kept)

        file_reports.append(
            {
                "path": str(path),
                "before": len(rows),
                "after": len(kept),
                "removed": len(removed),
                "removed_vqa_ids": removed_ids,
                "affected_ids_absent": missing_ids,
            }
        )

    return {
        "backup_dir": str(backup_dir) if apply else None,
        "total_removed_rows": total_removed,
        "removed_count_distribution": {str(key): hit_counts[key] for key in sorted(hit_counts)},
        "files": file_reports,
    }


def load_jsonl(path: Path) -> list[dict[str, Any]]:
    rows: list[dict[str, Any]] = []
    with path.open("r", encoding="utf-8") as f:
        for line in f:
            if line.strip():
                rows.append(json.loads(line))
    return rows


def write_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    with path.open("w", encoding="utf-8", newline="\n") as f:
        for row in rows:
            f.write(json.dumps(row, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    main()
